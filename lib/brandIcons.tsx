function buscarMarca(nomeSistema: string): MarcaIcone | null {
  const nome = nomeSistema.toLowerCase();
  for (const marca of MARCAS) {
    if (marca.keywords.some((k) => nome.includes(k))) return marca;
  }
  return null;
}

// Ícone de marca quando reconhecido; senão, um círculo com a inicial do
// nome (mesmo tratamento pra "ChatGPT"/"OpenAI" — sem ícone oficial
// disponível pra reuso, ver comentário no topo do arquivo).
export function SistemaIcone({ nome }: { nome: string }) {
  const marca = buscarMarca(nome);

  if (marca) {
    return (
      <svg
        viewBox="0 0 24 24"
        width="18"
        height="18"
        role="img"
        aria-label={marca.title}
        style={{ flexShrink: 0 }}
      >
        <title>{marca.title}</title>
        <path d={marca.path} fill={`#${marca.hex}`} />
      </svg>
    );
  }

  const inicial = nome.trim().charAt(0).toUpperCase() || "?";
  return (
    <span
      aria-hidden="true"
      style={{
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        width: "18px",
        height: "18px",
        borderRadius: "50%",
        background: "var(--border)",
        color: "var(--text-muted)",
        fontSize: "0.65rem",
        fontWeight: 700,
        flexShrink: 0,
      }}
    >
      {inicial}
    </span>
  );
}
